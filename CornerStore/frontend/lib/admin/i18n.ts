export type AdminI18nKey = keyof typeof dict;

export function adminT(key: AdminI18nKey, lang: Language, vars?: Record<string, string | number>) {
  let text = dict[key]?.[lang] ?? dict[key]?.en ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

